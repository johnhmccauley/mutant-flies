  for (var ch in FONTSRC) {
    var rows = FONTSRC[ch].split(","), bits = [];
    for (var y = 0; y < 8; y++) {
      var r = rows[y], m = 0;
      for (var x = 0; x < 8; x++) if (r.charAt(x) === "#") m |= (1 << x);
      bits.push(m);
    }
    FONT[ch] = bits;
  }

  /* PRINT TAB(cx,cy) - draw text on the 8x8 character grid */
  function print(ctx, str, cx, cy, colour) {
    ctx.fillStyle = colour;
    var px = cx * 8, py = cy * 8;
    for (var i = 0; i < str.length; i++) {
      var g = FONT[str.charAt(i)];
      if (g) {
        for (var y = 0; y < 8; y++) {
          var m = g[y];
          if (!m) continue;
          for (var x = 0; x < 8; x++) if (m & (1 << x)) ctx.fillRect(px + x, py + y, 1, 1);
        }
      }
      px += 8;
    }
  }

  /* centred within a 40-column MODE 1 screen */
  function centre(ctx, str, cy, colour) {
    print(ctx, str, Math.round((40 - str.length) / 2), cy, colour);
  }

